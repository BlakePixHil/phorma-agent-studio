/**
 * Converts a `ThemePalette` to the PrimeNG `primary` token shape expected by
 * `definePreset` / `updatePrimaryPalette`.
 */
export function toPrimaryToken(palette: ThemePalette): Record<string, string> {
  return { ...palette.ramp };
}
